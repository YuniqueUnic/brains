#!/bin/bash
# Regenerate every committed API artifact from api/brains.idl.
# Use scripts/install-xidlc.sh and select that binary with XIDLC.
set -euo pipefail
cd "$(dirname "$0")/.."
XIDLC=${XIDLC:?set XIDLC to the compiler installed by scripts/install-xidlc.sh}
command -v "$XIDLC" >/dev/null
expected=$(python3 - <<'PY'
import tomllib
with open("Cargo.toml", "rb") as manifest:
    workspace = tomllib.load(manifest)["workspace"]
print(workspace["dependencies"]["xidl-rust-axum"]["version"].removeprefix("="))
PY
)
actual=$("$XIDLC" --version)
if [[ "$actual" != "xidlc $expected" ]]; then
  echo "expected xidlc $expected, got $actual" >&2
  exit 1
fi
# Generate everything before publishing any output, so a rejected IDL cannot
# leave a previously valid SDK half-deleted.
generated_dir=$(mktemp -d)
trap 'rm -rf "$generated_dir"' EXIT
mkdir -p "$generated_dir"/{openapi,typescript,rust,contract}

"$XIDLC" gen --out-dir "$generated_dir/openapi" openapi api/brains.idl
mv "$generated_dir/openapi/openapi_brains.json" "$generated_dir/openapi/brains-openapi.json"
"$XIDLC" gen --out-dir "$generated_dir/typescript" typescript-rest api/brains.idl
"$XIDLC" gen --out-dir "$generated_dir/rust" rust-axum --client api/brains.idl
mv "$generated_dir/rust/brains.rs" "$generated_dir/rust/brains_generated.rs"
"$XIDLC" gen --out-dir "$generated_dir/contract" rust-axum --server api/brains.idl
python3 - "$generated_dir" <<'PYFORMAT'
from pathlib import Path
import sys
root = Path(sys.argv[1])
header = "// Code generated by xidlc from api/brains.idl (scripts/gen-api.sh). DO NOT EDIT.\n\n"
for path in [root / "rust/brains_generated.rs", root / "contract/brains.rs"]:
    path.write_text(header + path.read_text())
# Format only; no wire semantics or generated identifiers are rewritten.
for path in (root / "typescript").glob("*.ts"):
    path.write_text("\n".join(line.rstrip() for line in path.read_text().splitlines()) + "\n")
PYFORMAT
rustfmt --edition 2024 "$generated_dir/rust/brains_generated.rs" "$generated_dir/contract/brains.rs"
rm -rf sdk/openapi sdk/typescript crates/api-http/src/contract
mv "$generated_dir/openapi" sdk/openapi
mv "$generated_dir/typescript" sdk/typescript
mv "$generated_dir/contract" crates/api-http/src/contract
mv "$generated_dir/rust/brains_generated.rs" sdk/rust/src/brains_generated.rs

echo "sdk/ regenerated from api/brains.idl with $actual"
python3 scripts/check-api-paths.py
