#!/bin/bash
# Regenerate every committed API artifact from api/brains.idl.
# Requires xidlc with the @http exception/union support (xidl#294/#296):
#   cargo install xidlc --locked --features cli,fmt   (once upstream lands)
# or point XIDLC at a local build of the feature branches.
set -euo pipefail
cd "$(dirname "$0")/.."
XIDLC="${XIDLC:-$HOME/.cargo/bin/xidlc}"
command -v "$XIDLC" >/dev/null || XIDLC=xidlc

rm -rf sdk/openapi sdk/typescript
mkdir -p sdk/openapi sdk/typescript sdk/rust/src

"$XIDLC" gen --out-dir sdk/openapi openapi api/brains.idl
mv sdk/openapi/openapi_brains.json sdk/openapi/brains-openapi.json

"$XIDLC" gen --out-dir sdk/typescript typescript-rest api/brains.idl

# One generation covers types + client (module types live in the client).
"$XIDLC" gen --out-dir sdk/rust/src rust-axum --client api/brains.idl
mv sdk/rust/src/brains.rs sdk/rust/src/brains_generated.rs
header='// Code generated by xidlc from api/brains.idl (scripts/gen-api.sh). DO NOT EDIT.'
printf '%s\n\n' "$header" | cat - sdk/rust/src/brains_generated.rs > /tmp/brains-gen-tmp
mv /tmp/brains-gen-tmp sdk/rust/src/brains_generated.rs

# The server skeleton (trait + DTO types + axum router) the api-http crate
# implements.
rm -rf crates/api-http/src/contract
mkdir -p crates/api-http/src/contract
"$XIDLC" gen --out-dir crates/api-http/src/contract rust-axum --server api/brains.idl
printf '%s\n\n' "$header" | cat - crates/api-http/src/contract/brains.rs > /tmp/brains-gen-tmp
mv /tmp/brains-gen-tmp crates/api-http/src/contract/brains.rs

echo "sdk/ regenerated from api/brains.idl"
