"""Post-process the xidlc rust-axum client forBrains' conditional writes.

xidlc 0.96 emits module types in the rust-axum client (upstream fix
xidl#295 part 1), but @optional request headers are still passed straight
into HeaderValue::from_str(&Option<String>) — the reference never coerces
and absent headers would still be INSERTED (xidl#295 part 2, still open).
This pass wraps those inserts in `if let Some` so an absent conditional
header is simply not sent.
"""
from pathlib import Path

OPTIONAL_HEADERS = {"if_match", "if_none_match", "operation_id", "content_sha256", "csrf_token"}

source = Path("/tmp/brains-sdk-rs/brains.rs")
lines = source.read_text().split("\n")
out = []
i = 0
while i < len(lines):
    line = lines[i]
    out.append(line)
    stripped = line.strip()
    param = stripped.removeprefix("let header_value_str = ").removesuffix(";").strip()
    if param in OPTIONAL_HEADERS:
        j = i + 1
        while j < len(lines) and "req.headers_mut().insert(header_name, header_value);" not in lines[j]:
            j += 1
        if j < len(lines):
            indent = " " * 12
            out.append(indent + "if let Some(header_value_str) = header_value_str.clone() {")
            for k in range(i + 1, j + 1):
                out.append(indent + lines[k])
            out.append(indent + "}")
            i = j + 1
            continue
    i += 1

header = "// Code generated by xidlc from api/brains.idl (scripts/gen-api.sh). DO NOT EDIT.\n"
Path("sdk/rust/src/brains_generated.rs").write_text(header + "\n".join(out))
print("patched rust sdk:", len(out), "lines")
