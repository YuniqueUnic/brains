"""Merge xidlc rust (types) + rust-axum --client (client) into one module."""
from pathlib import Path

def module_body(path: Path) -> str:
    text = path.read_text()
    start = text.index("pub mod ")
    open_brace = text.index("{", start)
    depth = 0
    for i in range(open_brace, len(text)):
        if text[i] == "{":
            depth += 1
        elif text[i] == "}":
            depth -= 1
            if depth == 0:
                return text[open_brace + 1 : i]
    raise SystemExit(f"unbalanced module in {path}")

types_file = next(Path("/tmp/brains-sdk-types").glob("*.rs"))
types_body = module_body(types_file).rstrip()
client = Path("/tmp/brains-sdk-rs/brains.rs").read_text()
marker = "pub mod brains {\n"
assert marker in client, "client module marker missing"
merged = client.replace(marker, marker + types_body + "\n\n", 1)

# xidlc 0.95 passes @optional request headers straight into
# HeaderValue::from_str(&Option<String>) — wrap those inserts in
# `if let Some` so absent headers are simply not sent.
OPTIONAL_HEADERS = {"if_match", "if_none_match", "operation_id", "content_sha256", "csrf_token"}
lines = merged.split("\n")
out = []
i = 0
while i < len(lines):
    line = lines[i]
    out.append(line)
    stripped = line.strip()
    param = stripped.removeprefix("let header_value_str = ").removesuffix(";").strip()
    if param in OPTIONAL_HEADERS:
        j = i + 1
        while j < len(lines) and "req.headers_mut().insert(header_name, header_value);" not in lines[j]:
            j += 1
        if j < len(lines):
            indent = " " * 12
            out.append(indent + "if let Some(header_value_str) = header_value_str.clone() {")
            for k in range(i + 1, j + 1):
                out.append(indent + lines[k])
            out.append(indent + "}")
            i = j + 1
            continue
    i += 1
merged = "\n".join(out)
header = "// Code generated by xidlc from api/brains.idl (scripts/gen-api.sh). DO NOT EDIT.\n"
Path("sdk/rust/src/brains_generated.rs").write_text(header + merged)
print("merged rust sdk:", len(merged.splitlines()), "lines")
